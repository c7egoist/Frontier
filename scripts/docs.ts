/**
 * Generates docs/SOUNDS.md and docs/audio-report.md from the catalog and the
 * latest measurement run. Run after changing sounds or levels:
 *
 *   npm run docs
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { SOUNDS, SOUND_CATEGORIES } from '../src/catalog';

const root = process.cwd();
const docsDir = resolve(root, 'docs');
mkdirSync(docsDir, { recursive: true });

const reportPath = resolve(root, 'scripts/audio-report.json');
interface ReportRow {
  id: string;
  peakDb: number;
  rmsDb: number;
  lufs: number;
  measured: number;
}
const report: ReportRow[] = existsSync(reportPath)
  ? JSON.parse(readFileSync(reportPath, 'utf8'))
  : [];
const byId = new Map(report.map((row) => [row.id, row]));

const lines: string[] = [];
lines.push('# Sound catalog');
lines.push('');
lines.push(
  `**${SOUNDS.length} procedural sounds** across ${SOUND_CATEGORIES.length} categories. ` +
    'Every sound is synthesised at playback time — there are no audio assets in this repository.',
);
lines.push('');
lines.push('Generated by `npm run docs` from `src/catalog`. Do not edit by hand.');
lines.push('');
lines.push('## Index');
lines.push('');
for (const category of SOUND_CATEGORIES) {
  const count = SOUNDS.filter((sound) => sound.category === category.id).length;
  lines.push(`- [${category.name}](#${category.name.toLowerCase()}) — ${count} sounds. ${category.description}`);
}
lines.push('');

for (const category of SOUND_CATEGORIES) {
  const sounds = SOUNDS.filter((sound) => sound.category === category.id);
  if (!sounds.length) continue;
  lines.push(`## ${category.name}`);
  lines.push('');
  lines.push(category.description);
  lines.push('');
  lines.push('| Sound | ID | Length | Character | Tags |');
  lines.push('| --- | --- | ---: | --- | --- |');
  for (const sound of sounds) {
    const measured = byId.get(sound.id);
    const length = measured ? `${sound.duration.toFixed(2)} s` : `${sound.duration.toFixed(2)} s`;
    lines.push(
      `| **${sound.name}** | \`${sound.id}\` | ${length} | ${sound.description} | ${sound.tags
        .map((tag) => `\`${tag}\``)
        .join(' ')} |`,
    );
  }
  lines.push('');
}

lines.push('## Aliases');
lines.push('');
lines.push(
  'Lookup is case- and separator-insensitive (`power_on`, `Power-On` and `powerOn` all resolve), ' +
    'and the following friendly aliases are built in:',
);
lines.push('');
const { SOUND_ALIASES } = await import('../src/catalog');
for (const [alias, target] of Object.entries(SOUND_ALIASES)) {
  lines.push(`- \`${alias}\` → \`${target}\``);
}
lines.push('');
writeFileSync(resolve(docsDir, 'SOUNDS.md'), `${lines.join('\n')}\n`);
console.log(`docs/SOUNDS.md (${SOUNDS.length} sounds)`);

if (report.length) {
  const maxPeak = Math.max(...report.map((r) => r.peakDb));
  const md: string[] = [];
  md.push('# Measured audio report');
  md.push('');
  md.push(
    'Generated by `npm run measure` using `web-audio-engine` to render each sound offline through ' +
      'the production graph (master bus, reverb and compressor included). Loudness is an ' +
      'ITU-R BS.1770-style K-weighted estimate over the full sound; it is used for relative ' +
      'comparison, not broadcast conformance.',
  );
  md.push('');
  md.push(`- Sounds measured: **${report.length}**`);
  md.push(
    `- Highest peak: **${maxPeak.toFixed(1)} dBFS** (ceiling −0.1 dBFS; designed peaks range −6 to −28 dBFS)`,
  );
  md.push('- Level trims are stored in `src/catalog/levels.ts` and applied per sound.');
  md.push('');
  md.push('| Sound | Peak (dBFS) | RMS (dBFS) | K-weighted (LUFS) | Audible length |');
  md.push('| --- | ---: | ---: | ---: | ---: |');
  for (const row of report) {
    md.push(
      `| \`${row.id}\` | ${row.peakDb.toFixed(1)} | ${row.rmsDb.toFixed(1)} | ${row.lufs.toFixed(1)} | ${row.measured.toFixed(2)} s |`,
    );
  }
  md.push('');
  writeFileSync(resolve(docsDir, 'audio-report.md'), `${md.join('\n')}\n`);
  console.log(`docs/audio-report.md (${report.length} rows)`);
}
