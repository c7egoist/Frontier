function ConstructSlatePreset(Entry)
{
    const S = Entry.spec;
    const Scale = Math.min(1.30, Math.max(0.45, 2048.0 / (S.worldSize || 2048.0)));
    const Pal = SlatePalettes[S.palette] || SlatePalettes.granite;
    const MtnH = Math.round(Math.max(25.0, S.mountainHeight * Scale));
    const BaseEl = Math.round(S.baseElevation * Scale);
    const CliffH = Math.round((S.cliffHeight || 0) * (S.worldSize === 1024 ? 1.55 : Scale));
    const PlatH = Math.round((S.plateauHeight || 340) * (S.worldSize === 1024 ? 1.35 : Scale));
    const CanDepth = Math.round((S.canyonDepth || 0) * Scale);
    const StackH = Math.round((S.stackHeight || 0) * (S.worldSize === 1024 ? 1.25 : Scale));
    const WaterLvl = S.waterEnabled ? Math.max(-20, Math.round(S.seaLevel * Scale + (S.cliffHeight > 40 ? 32 : 12))) : -80;

    const Features = [];
    if (StackH > 0) Features.push("Gaea-style tiered rock stacks");
    if (CliffH > 0) Features.push("sheer escarpment cliffs" + (S.cliffStacks > 0 ? " & sea stacks" : ""));
    if (S.plateauStrength > 0.25) Features.push("mesa caprock plateau");
    if (CanDepth > 0) Features.push("entrenched meandering canyon");
    if (S.duneAmount > 2) Features.push("33° slip-face barchanoid dunes");
    if (S.outcropDensity > 0.05) Features.push("superellipsoid core-stone tors");
    if (S.strataStrength > 0.25) Features.push("dipping stratigraphic bed packages");
    if (S.ruggedAmount > 2) Features.push("3D push–pull cliff buttresses");
    const Blurb = "Ported from Slate (" + S.palette + " province): " + (Features.slice(0, 4).join(", ") || "warped ridged massif & fluvial erosion") + ", shaded with data-driven AO/protrusion/flow splatting.";

    return {
        Id: Entry.id,
        Label: Entry.label,
        Region: Entry.region,
        Category: Entry.category,
        Origin: "Slate",
        ThumbSpec: S,
        Blurb: Blurb,
        SeedMark: Entry.seed,
        BuildLayers: () =>
        {
            const Layers =
            [
                ConstructLayer("SlateLandform", {
                    Label: Entry.label + " landform", Blend: "Replace", Seed: Entry.seed,
                    Params: {
                        MountainHeight: MtnH,
                        BaseElevation: BaseEl,
                        BaseFrequency: S.baseFrequency,
                        RidgeSharpness: S.ridgeSharpness,
                        PeakPower: S.peakPower,
                        WarpStrength: S.warpStrength,
                        ReliefFrequency: S.reliefFrequency,
                        ReliefContrast: S.reliefContrast,
                        CliffHeight: CliffH,
                        CliffSharpness: Math.min(1.2, S.cliffSharpness),
                        CliffStacks: S.cliffStacks || 0,
                        PlateauStrength: S.plateauStrength || 0,
                        PlateauHeight: PlatH,
                        CanyonDepth: CanDepth,
                        CanyonWidth: S.canyonWidth > 20 ? S.canyonWidth : 320,
                        DuneAmount: S.duneAmount > 2 ? S.duneAmount : 0,
                        DuneWavelength: S.duneWavelength || 140,
                        DuneDirection: S.duneDirection || 35,
                        DuneAsymmetry: S.duneAsymmetry || 0.72,
                        DuneCoverage: S.duneCoverage || 0.65,
                    },
                }),
            ];
            if (StackH > 0)
            {
                Layers.push(ConstructLayer("RockStacks", {
                    Label: "Tiered rock stacks", Seed: Entry.seed + 7,
                    Params: {
                        StackHeight: StackH,
                        StackLevels: S.stackLevels,
                        StackScale: S.stackScale < 15 ? 145 : S.stackScale,
                        StackTaper: Math.min(0.45, S.stackTaper),
                        StackSharpness: Math.max(0.88, S.stackSharpness),
                        StackChaos: S.stackChaos,
                        StackSpires: S.stackSpires,
                        StackCoverage: S.stackCoverage,
                        StackPedestal: S.stackPedestal,
                        StackSizeVar: S.stackSizeVar,
                        StackElongation: S.stackElongation,
                        StackCluster: S.stackCluster,
                    },
                }));
            }
            if (S.outcropDensity > 0.02)
            {
                Layers.push(ConstructLayer("BoulderTors", {
                    Label: "Core-stone boulder tors", Seed: Entry.seed + 13,
                    Params: {
                        Density: S.outcropDensity,
                        Size: S.outcropSize,
                        Spacing: S.outcropSpacing,
                        Count: S.outcropCount,
                        RidgeBias: S.outcropRidge,
                        SlopeMax: S.outcropSlopeMax,
                        Weather: S.outcropWeather,
                    },
                }));
            }
            if (S.strataStrength > 0.05)
            {
                Layers.push(ConstructLayer("StrataTerrace", {
                    Label: "Stratigraphic bed packages", Seed: Entry.seed + 19,
                    Params: {
                        BandMetres: Math.max(6, Math.round(S.strataBand * (S.worldSize === 1024 ? 1.6 : 1.0))),
                        TerraceStrength: Math.min(0.92, S.strataStrength),
                        HardContrast: S.hardnessContrast,
                        Dip: S.strataDip,
                        DipDirection: S.strataDipDirection,
                        Variation: S.strataVariation,
                        Packaging: S.strataPackaging,
                        HardShare: S.strataHardShare,
                        Lateral: S.strataLateral,
                        RiserWidth: 0.38,
                    },
                }));
            }
            if (S.ruggedOn && S.ruggedAmount > 0.5 && S.duneAmount < 20)
            {
                Layers.push(ConstructLayer("RuggedPushPull", {
                    Label: "3D push–pull cliff faces", Seed: Entry.seed + 29,
                    Params: {
                        Amount: Math.min(22, S.ruggedAmount * 1.05),
                        Scale: Math.max(38, S.ruggedScale),
                        Blockiness: S.ruggedBlockiness,
                        Ledges: S.ruggedLedges,
                        Bands: S.ruggedBands,
                        SlopeMin: S.ruggedSlope,
                    },
                }));
            }
            if (S.fluvialStrength > 0.05)
            {
                Layers.push(ConstructLayer("FluvialIncision", {
                    Label: "Drainage & stream incision", Seed: Entry.seed + 37,
                    Params: {
                        Strength: Math.min(2.6, S.fluvialStrength * 2.4),
                        Iterations: Math.max(2, Math.min(5, Math.round((S.fluvialStrength || 0.6) * 5))),
                        Sedimentation: S.fluvialDeposition,
                        Capacity: 1.08,
                    },
                }));
            }
            if (S.droplets > 10000)
            {
                Layers.push(ConstructLayer("HydraulicErosion", {
                    Label: "Rill & slope wash", Seed: Entry.seed + 43,
                    Params: {
                        Droplets: Math.min(180000, S.droplets),
                        Inertia: 0.24,
                        Capacity: 4.1,
                        ErodeRate: Math.min(0.42, S.erodeSpeed),
                        DepositRate: Math.min(0.42, S.depositSpeed),
                        Radius: 2,
                    },
                }));
            }
            Layers.push(ConstructLayer("ThermalErosion", {
                Label: "Talus & cliff angle repose", Seed: Entry.seed + 53,
                Params: {
                    Iterations: Math.min(56, Math.max(16, S.thermalIterations * 1.4)),
                    TalusAngle: S.talusSoft,
                    CliffAngle: Math.min(84, S.talusHard),
                    Rate: 0.48,
                },
            }));
            if (S.snowOn && S.snowLine < 1800)
            {
                Layers.push(ConstructLayer("SnowAccumulation", {
                    Label: "Highland snowpack", Seed: Entry.seed + 61,
                    Params: {
                        Snowline: Math.round(S.snowLine * Scale * 0.78),
                        Band: 75,
                        SlopeLimit: Math.min(56, S.snowSlope),
                        Depth: 4.0,
                    },
                }));
            }
            if (CliffH > 40 || StackH > 60 || CanDepth > 100)
            {
                Layers.push(ConstructLayer("CaveNetwork", {
                    Label: "3D cliff undercut caves (SDF)", Seed: Entry.seed + 71,
                    Params: { CaveCount: 2, Aperture: 16, TunnelDepth: 76, Blend: 7 },
                }));
            }
            return Layers;
        },
        Environment: Environment({
            ...Pal,
            SunAzimuth: S.sunAzimuth,
            SunElevation: Math.max(22, S.sunElevation),
            SunIntensity: 3.3,
            WaterLevel: WaterLvl,
            FogDensity: 0.000065 + (S.fogDensity || 0.25) * 0.00008,
            Vegetation: S.vegetation,
            StrataContrast: Math.min(0.95, (S.strataStrength || 0.5) * (S.hardnessContrast || 0.7)),
        }),
        Stamps: [],
        Camera: { Azimuth: -36, Elevation: 23, Distance: 2150 },
    };
}

