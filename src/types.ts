/**
 * Public type surface for Frontier Audio.
 *
 * The library is intentionally engine-agnostic at the type level: it works
 * against any `BaseAudioContext`, which lets the exact same procedural sound
 * graph run through a live `AudioContext` or an `OfflineAudioContext`
 * (used for waveform previews, WAV export and the test suite).
 */

export type SoundCategory =
  | 'core'
  | 'navigation'
  | 'feedback'
  | 'system'
  | 'cinematic'
  | 'data'
  | 'status';

export interface SoundMeta {
  /** Stable identifier, e.g. `powerOn`. Lookup is case/format insensitive. */
  id: string;
  /** Human readable name, e.g. "Power On". */
  name: string;
  category: SoundCategory;
  /** One line description of what the sound conveys. */
  description: string;
  /** Nominal length in seconds (including reverb tail). */
  duration: number;
  /** Free-form tags used by search / auditing. */
  tags: string[];
  /** Number of micro-variations generated by the synth (for humans). */
  variants?: number;
  /** Minimum spacing in ms between two plays of this sound. */
  minInterval?: number;
}

export interface PlayOptions {
  /** Linear gain multiplier for this voice. Default 1. */
  volume?: number;
  /** Pitch/filter-rate multiplier (0.5 = octave down). Does not stretch time. */
  rate?: number;
  /** Stereo offset -1..1, added to the sound's built-in placement. */
  pan?: number;
  /** Reverb send override 0..1. */
  space?: number;
  /** Delay in seconds relative to now. */
  when?: number;
  /** Adds subtle per-play pitch/level/pan drift. Default true. */
  humanize?: boolean;
  /** Bypass the per-sound min-interval throttle. Default false. */
  force?: boolean;
  /** Seed the variation RNG for deterministic playback. */
  seed?: number;
}

export interface AudioEngineOptions {
  /** Master volume 0..1. Default 0.8. */
  volume?: number;
  /** Start muted. Default false. */
  muted?: boolean;
  /** Hard ceiling on concurrent voices (oldest is stolen). Default 24. */
  maxVoices?: number;
  /** Resume the context on the first pointer/key gesture. Default true. */
  autoUnlock?: boolean;
  /** Reuse an existing context (e.g. a host app's). */
  context?: BaseAudioContext;
  /** Global reverb mix multiplier 0..1. Default 1. */
  space?: number;
  /** Kill switch for audio (useful in CI, SSR or "sound off" settings). */
  enabled?: boolean;
  /** Base seed for the humanizer. */
  seed?: number;
}

export type EngineState =
  | 'uninitialized'
  | 'suspended'
  | 'running'
  | 'closed'
  | 'unsupported';

export interface FilterOptions {
  type?: BiquadFilterType;
  /** Start frequency in Hz. */
  f: number;
  /** End frequency in Hz; creates an exponential sweep across the envelope. */
  f1?: number;
  /** Q / resonance. */
  q?: number;
  /** Gain in dB for shelving/peaking filters. */
  gain?: number;
  /** Delay in seconds relative to the voice start. */
  when?: number;
  /** Sweep time in seconds. Defaults to the source envelope length. */
  sweepTime?: number;
}

export interface ToneOptions {
  freq: number;
  type?: OscillatorType;
  /** Envelope length in seconds. Default 0.2. */
  dur?: number;
  /** Peak linear gain. Default 0.15. */
  gain?: number;
  attack?: number;
  hold?: number;
  release?: number;
  /** Exponential glide target in Hz. */
  glideTo?: number;
  /** Glide time in seconds. Defaults to `dur`. */
  glideTime?: number;
  detune?: number;
  pan?: number;
  when?: number;
  filter?: FilterOptions | FilterOptions[];
  /** Vibrato in cents. */
  vibrato?: { rate: number; depth: number };
  /** 0 = pure exponential decay, 1 = hold then release. Default 0. */
  sustain?: number;
}

export interface NoiseOptions {
  dur?: number;
  gain?: number;
  attack?: number;
  hold?: number;
  release?: number;
  pan?: number;
  when?: number;
  color?: 'white' | 'pink';
  filter?: FilterOptions | FilterOptions[];
}

export interface BellOptions {
  freq: number;
  dur?: number;
  gain?: number;
  /** Inharmonicity ratio of the modulator. 2 is glassy, 3.5 is metallic. */
  ratio?: number;
  /** Modulation index (in Hz of peak deviation). */
  index?: number;
  attack?: number;
  pan?: number;
  when?: number;
}

export interface ThumpOptions {
  freq?: number;
  dur?: number;
  gain?: number;
  /** Pitch drop start multiplier. Default 2.4. */
  drop?: number;
  pan?: number;
  when?: number;
}

export interface PluckOptions {
  freq: number;
  dur?: number;
  gain?: number;
  when?: number;
  pan?: number;
  brightness?: number;
}
