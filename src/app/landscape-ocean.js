/**
 * GPU shallow-water simulation for the Landscape Studio ocean.
 *
 * Physics: the same family of solver the existing Terrain Studio water uses —
 * a Mei-style virtual-pipe shallow-water model, not a scrolling normal map. Water
 * depth is a persistent state texture; four pipe fluxes are recomputed from the
 * surface-head difference every step; the flux divergence updates depth; depth-
 * averaged velocity is Froude-limited.
 *
 * Differences that matter for a continent-scale coast:
 *   - Bed height comes from the authored SDF field, so a 300 km shelf and a
 *     4 m beach crest are the same input.
 *   - The domain border is a wave maker that relaxes toward an incoming swell
 *     field, so waves enter the domain and run up real beaches.
 *   - Whitewater (G channel) is persistent: generated by breaking, uprush and
 *     impact; advected with the simulated velocity; diffused; decayed. It is
 *     then uploaded to the ocean material as a foam field, which is why surf
 *     appears where the water actually piles up instead of everywhere shallow.
 *   - The simulation domain follows the camera. Because it is re-seeded from the
 *     analytic bed and a deterministic swell phase, following the camera costs
 *     one texture upload, not a re-simulation of the world.
 */

import * as THREE from 'three';
import { OCEAN_FRAGMENT, OCEAN_VERTEX } from './landscape-shaders.js';

/**
 * The simulation's own solver. Kept in one string so the flux, integrate and
 * foam passes share exactly the same bed/terrain accessors.
 */
const OCEAN_COMMON_GLSL = /* glsl */`
uniform sampler2D uBedTex;    // r = bed elevation m, g = oceanConnectivity 0..1
uniform vec4 uDomain;         // textureSize, cellSize m, spanMeters, seaLevel m
uniform vec4 uSim;            // dt sec, time sec, gravity, foamLifetime sec
uniform vec4 uWaveA;          // dirX, dirZ, waveHeight m, wavelength m
uniform vec4 uWaveB;          // surfStrength, waveMakerStrength, foamThreshold, enabled

float bedAt(ivec2 c) {
  ivec2 cc = clamp(c, ivec2(0), ivec2(int(uDomain.x) - 1));
  return texelFetch(uBedTex, cc, 0).r;
}

float oceanMaskAt(ivec2 c) {
  ivec2 cc = clamp(c, ivec2(0), ivec2(int(uDomain.x) - 1));
  return texelFetch(uBedTex, cc, 0).g;
}

vec2 cellWorld(ivec2 c) {
  return (vec2(c) / max(1.0, uDomain.x - 1.0) - 0.5) * uDomain.z;
}

float waveEta(vec2 worldXZ) {
  vec2 dir = normalize(uWaveA.xy + vec2(1e-5));
  float k = 6.2831853 / max(20.0, uWaveA.w);
  // Virtual pipes propagate near sqrt(g * cell); driving the reservoir at the
  // solver's own celerity is what lets boundary swell actually cross the shelf.
  float omega = sqrt(max(0.2, uSim.z) * max(1.0, uDomain.y)) * k;
  float phase = dot(dir, worldXZ) * k - uSim.y * omega;
  float group = 0.55 + 0.45 * sin(dot(dir, worldXZ) * 0.006 - uSim.y * 0.11);
  return uWaveA.z * group * (0.72 * sin(phase) + 0.28 * sin(phase * 1.73 + 1.7));
}
`;

const OCEAN_INIT_FRAG = /* glsl */`
${OCEAN_COMMON_GLSL}

void main() {
  ivec2 c = ivec2(gl_FragCoord.xy);
  float bed = bedAt(c);
  float connected = oceanMaskAt(c);
  float restingDepth = max(0.0, uDomain.w - bed);
  float eta = waveEta(cellWorld(c)) * smoothstep(0.5, 7.0, restingDepth);
  float depth = connected * max(0.0, uDomain.w + eta - bed);
  gl_FragColor = vec4(depth, 0.0, 0.0, 0.0);
}
`;

const OCEAN_FLUX_FRAG = /* glsl */`
${OCEAN_COMMON_GLSL}
uniform sampler2D uStateTex;
uniform sampler2D uFluxTex;

vec4 stateAt(ivec2 c) {
  ivec2 cc = clamp(c, ivec2(0), ivec2(int(uDomain.x) - 1));
  return texelFetch(uStateTex, cc, 0);
}

void main() {
  ivec2 c = ivec2(gl_FragCoord.xy);
  int maxI = int(uDomain.x) - 1;
  float cell = uDomain.y;
  float dt = max(1e-4, uSim.x);
  float bedC = bedAt(c);
  float depth = max(0.0, stateAt(c).r);
  if (depth <= 1e-6 || uWaveB.w < 0.5) {
    gl_FragColor = vec4(0.0);
    return;
  }

  float surfC = bedC + depth;
  float surfR = bedAt(c + ivec2(1, 0)) + max(0.0, stateAt(c + ivec2(1, 0)).r);
  float surfL = bedAt(c + ivec2(-1, 0)) + max(0.0, stateAt(c + ivec2(-1, 0)).r);
  float surfU = bedAt(c + ivec2(0, 1)) + max(0.0, stateAt(c + ivec2(0, 1)).r);
  float surfD = bedAt(c + ivec2(0, -1)) + max(0.0, stateAt(c + ivec2(0, -1)).r);
  vec4 dh = vec4(surfC - surfR, surfC - surfL, surfC - surfU, surfC - surfD);

  // Domain edge behaves as an open ocean reservoir, not a wall.
  float outside = uDomain.w + waveEta(cellWorld(c));
  if (c.x == maxI) dh.x = surfC - outside;
  if (c.x == 0) dh.y = surfC - outside;
  if (c.y == maxI) dh.z = surfC - outside;
  if (c.y == 0) dh.w = surfC - outside;

  float area = cell * cell;
  vec4 oldFlux = texelFetch(uFluxTex, c, 0);
  float frictionRate = 0.48 + 2.1 * exp(-depth * 1.25);
  float retain = exp(-frictionRate * dt);
  vec4 flux = max(vec4(0.0), oldFlux * retain + dh * (dt * area * uSim.z / cell));

  float sumFlux = flux.x + flux.y + flux.z + flux.w;
  if (sumFlux > 1e-7) {
    float volumeAvailable = depth * area / dt;
    float maxDh = max(max(dh.x, dh.y), max(dh.z, dh.w));
    float antiOvershoot = max(maxDh, 0.0) * area * 0.5 / dt;
    float cap = min(volumeAvailable, antiOvershoot);
    if (sumFlux > cap) flux *= cap / sumFlux;
  }
  gl_FragColor = flux;
}
`;

const OCEAN_INTEGRATE_FRAG = /* glsl */`
${OCEAN_COMMON_GLSL}
uniform sampler2D uStateTex;
uniform sampler2D uFluxTex;

vec4 stateAt(ivec2 c) {
  ivec2 cc = clamp(c, ivec2(0), ivec2(int(uDomain.x) - 1));
  return texelFetch(uStateTex, cc, 0);
}

vec4 fluxAt(ivec2 c) {
  ivec2 cc = clamp(c, ivec2(0), ivec2(int(uDomain.x) - 1));
  return texelFetch(uFluxTex, cc, 0);
}

void main() {
  ivec2 c = ivec2(gl_FragCoord.xy);
  int maxI = int(uDomain.x) - 1;
  float cell = uDomain.y;
  float dt = max(1e-4, uSim.x);
  float bed = bedAt(c);
  vec4 old = stateAt(c);
  vec4 fC = fluxAt(c);

  float inL = c.x > 0 ? fluxAt(c + ivec2(-1, 0)).x : 0.0;
  float inR = c.x < maxI ? fluxAt(c + ivec2(1, 0)).y : 0.0;
  float inD = c.y > 0 ? fluxAt(c + ivec2(0, -1)).z : 0.0;
  float inU = c.y < maxI ? fluxAt(c + ivec2(0, 1)).w : 0.0;
  float totalIn = inL + inR + inD + inU;
  float totalOut = fC.x + fC.y + fC.z + fC.w;
  float dDepth = uWaveB.w > 0.5 ? dt * (totalIn - totalOut) / (cell * cell) : 0.0;
  float depth = max(0.0, old.r + dDepth);

  float qX = 0.5 * ((inL - fC.y) + (fC.x - inR)) / cell;
  float qZ = 0.5 * ((inD - fC.w) + (fC.z - inU)) / cell;
  float avgDepth = max(0.08, old.r + 0.5 * dDepth);
  float vMax = 1.35 + 2.9 * sqrt(avgDepth);
  vec2 velocity = clamp(vec2(qX, qZ) / avgDepth, vec2(-vMax), vec2(vMax));
  if (depth <= 0.001) velocity = vec2(0.0);
  float speed = length(velocity);

  // --- Reservoir / wave maker at the domain border ---------------------------------
  vec2 worldXZ = cellWorld(c);
  float edgeCells = float(min(min(c.x, c.y), min(maxI - c.x, maxI - c.y)));
  float edgeDistance = edgeCells * cell;
  float restingDepth = max(0.0, uDomain.w - bed);
  float maker = oceanMaskAt(c)
    * smoothstep(5.0, 18.0, restingDepth)
    * (1.0 - smoothstep(uDomain.z * 0.035, uDomain.z * 0.16, edgeDistance));
  float targetDepth = max(0.0, uDomain.w + waveEta(worldXZ) - bed);
  float relax = 1.0 - exp(-dt * (0.7 + 4.5 * uWaveB.y));
  depth = mix(depth, targetDepth, clamp(maker * relax * uWaveB.y, 0.0, 1.0));

  // --- Persistent whitewater -------------------------------------------------------
  vec2 texel = vec2(1.0 / max(1.0, uDomain.x - 1.0));
  vec2 backUv = clamp(gl_FragCoord.xy / max(1.0, uDomain.x) - velocity * dt / max(1.0, uDomain.z),
                      texel, vec2(1.0) - texel);
  float foamAdvected = texture2D(uStateTex, backUv).g;
  float foamNeighbours = 0.25 * (
    stateAt(c + ivec2(1, 0)).g + stateAt(c + ivec2(-1, 0)).g +
    stateAt(c + ivec2(0, 1)).g + stateAt(c + ivec2(0, -1)).g
  );
  float foam = mix(foamAdvected, foamNeighbours, 0.035);
  float foamDecayRate = mix(0.45, 1.0, smoothstep(0.03, 0.8, depth));
  foam *= exp(-dt * foamDecayRate / max(0.25, uSim.w));
  if (depth < 0.012) foam *= exp(-dt * 1.7);

  vec2 bedGradient = vec2(
    bedAt(c + ivec2(1, 0)) - bedAt(c + ivec2(-1, 0)),
    bedAt(c + ivec2(0, 1)) - bedAt(c + ivec2(0, -1))
  ) / (2.0 * cell);
  float bedSlope = length(bedGradient);
  vec2 uphill = bedSlope > 1e-5 ? bedGradient / bedSlope : vec2(0.0);
  float shorewardSpeed = dot(velocity, uphill);
  float surface = bed + depth;
  float eta = surface - uDomain.w;
  float froude = speed / sqrt(max(0.2, uSim.z) * max(0.08, depth));
  float shallow = 1.0 - smoothstep(2.5, 9.0, depth);
  float breaker = smoothstep(0.12, 0.42, abs(eta) / max(0.18, depth))
    * smoothstep(0.2, 0.78, froude) * shallow;
  float uprush = smoothstep(0.05, 0.8, shorewardSpeed)
    * smoothstep(0.012, 0.1, depth)
    * (1.0 - smoothstep(0.55, 2.2, depth));
  float impact = smoothstep(0.18, 0.7, bedSlope)
    * smoothstep(0.25, 1.4, shorewardSpeed)
    * (1.0 - smoothstep(1.2, 4.0, depth));
  float foamSource = clamp(breaker * 1.3 + uprush * 0.95 + impact * 0.8, 0.0, 1.6);
  foam += (1.0 - clamp(foam, 0.0, 1.0))
    * (1.0 - exp(-foamSource * max(0.0, uWaveB.x) * dt * 5.5));
  foam = clamp(foam, 0.0, 1.0);
  if (depth <= 0.0005 && foamSource <= 0.001) foam *= 0.82;

  gl_FragColor = vec4(depth, foam, velocity.x, velocity.y);
}
`;

export class LandscapeOceanSimulation {
  /**
   * @param {THREE.WebGLRenderer} renderer
   * @param {THREE.Scene} scene
   * @param {{spanMeters:number, seaLevel:number, resolution:number}} options
   */
  constructor(renderer, scene, options = {}) {
    this.renderer = renderer;
    this.scene = scene;
    this.resolution = Math.max(32, Math.min(1024, Math.round(options.resolution ?? 384)));
    this.spanMeters = options.spanMeters ?? 40_000;
    this.seaLevel = options.seaLevel ?? 0;
    this.gravity = 9.81;
    this.foamLifetime = options.foamLifetime ?? 8.5;
    this.enabled = options.enabled !== false;
    this.settings = {
      waveHeight: options.waveHeight ?? 1.35,
      waveLength: options.waveLength ?? 148,
      waveDirectionDeg: options.waveDirectionDeg ?? 212,
      surfStrength: options.surfStrength ?? 1,
      waveMakerStrength: options.waveMakerStrength ?? 1,
      foamThreshold: options.foamThreshold ?? 0.55,
      speed: options.speed ?? 1,
      opacity: options.opacity ?? 0.9,
      showFoam: options.showFoam !== false,
      shallowColor: options.shallowColor ?? new THREE.Color('#2f8f83'),
      deepColor: options.deepColor ?? new THREE.Color('#0a2b3f'),
      clarity: options.clarity ?? 0.55,
      foam: options.foam ?? 0.75,
      choppiness: options.choppiness ?? 0.45,
      windSpeed: options.windSpeed ?? 11.5,
      detailAmplitude: options.detailAmplitude ?? 0.55,
    };

    this.offset = new THREE.Vector2(0, 0);
    this.accumulatedTime = 0;

    this.bedTexture = null;
    this._bedData = new Float32Array(this.resolution * this.resolution * 4);
    this._createTargets();
    this._createQuadScene();
    this._createMaterial();
  }

  _createTargets() {
    const size = this.resolution;
    const options = {
      type: THREE.HalfFloatType,
      format: THREE.RGBAFormat,
      minFilter: THREE.LinearFilter,
      magFilter: THREE.LinearFilter,
      wrapS: THREE.ClampToEdgeWrapping,
      wrapT: THREE.ClampToEdgeWrapping,
      depthBuffer: false,
      stencilBuffer: false,
      generateMipmaps: false,
    };
    this.stateA = new THREE.WebGLRenderTarget(size, size, options);
    this.stateB = new THREE.WebGLRenderTarget(size, size, options);
    this.fluxA = new THREE.WebGLRenderTarget(size, size, options);
    this.fluxB = new THREE.WebGLRenderTarget(size, size, options);
  }

  _createQuadScene() {
    this.quadScene = new THREE.Scene();
    this.quadCamera = new THREE.OrthographicCamera(-1, 1, 1, -1, 0, 1);

    const makePass = (fragmentShader, uniforms) => new THREE.ShaderMaterial({
      vertexShader: /* glsl */`
        precision highp float;
        void main() { gl_Position = vec4(position.xy, 0.0, 1.0); }
      `,
      fragmentShader,
      uniforms,
      depthTest: false,
      depthWrite: false,
    });

    this.initMaterial = makePass(OCEAN_INIT_FRAG, this._commonUniforms());
    this.fluxMaterial = makePass(OCEAN_FLUX_FRAG, {
      ...this._commonUniforms(),
      uStateTex: { value: null },
      uFluxTex: { value: null },
    });
    this.integrateMaterial = makePass(OCEAN_INTEGRATE_FRAG, {
      ...this._commonUniforms(),
      uStateTex: { value: null },
      uFluxTex: { value: null },
    });

    this.plane = new THREE.Mesh(new THREE.PlaneGeometry(2, 2), this.initMaterial);
    this.plane.frustumCulled = false;
    this.quadScene.add(this.plane);
  }

  _commonUniforms() {
    return {
      uBedTex: { value: this.bedTexture || null },
      uDomain: { value: new THREE.Vector4(this.resolution, this.spanMeters / this.resolution, this.spanMeters, this.seaLevel) },
      uSim: { value: new THREE.Vector4(1 / 60, 0, this.gravity, this.foamLifetime) },
      uWaveA: { value: new THREE.Vector4(0.7, 0.7, 1.35, 148) },
      uWaveB: { value: new THREE.Vector4(1, 1, 0.55, 1) },
    };
  }

  _createMaterial() {
    // One ocean material, built from the shared shader module so the renderer
    // and the QA tooling check exactly the same GLSL.
    this.surfaceMaterial = new THREE.ShaderMaterial({
      vertexShader: OCEAN_VERTEX,
      fragmentShader: OCEAN_FRAGMENT,
      uniforms: {
        // Simulated state
        uStateTex: { value: this.stateA.texture },
        uBedTex: { value: this.bedTexture || null },
        uDomain: { value: new THREE.Vector4(this.resolution, this.spanMeters / this.resolution, this.spanMeters, this.seaLevel) },
        uOceanOrigin: { value: new THREE.Vector3(0, 0, 0) },
        uShoalMax: { value: 45 },
        // Swell
        uTime: { value: 0 },
        uSwell: { value: new THREE.Vector4(0.7, 0.7, this.settings.waveHeight, this.settings.waveLength) },
        uChop: { value: new THREE.Vector4(this.settings.choppiness, this.settings.windSpeed, this.settings.detailAmplitude, this.seaLevel) },
        uOriginDrag: { value: new THREE.Vector2(0, 0) },
        // Shading
        uSeaLevel: { value: this.seaLevel },
        uSunDir: { value: new THREE.Vector3(0.5, 0.72, 0.4).normalize() },
        uSkyZenith: { value: new THREE.Color('#5d84b4') },
        uSkyHorizon: { value: new THREE.Color('#c3d3e0') },
        uShallowColor: { value: this.settings.shallowColor },
        uDeepColor: { value: this.settings.deepColor },
        uClarity: { value: this.settings.clarity },
        uFoamAmount: { value: this.settings.foam },
        uOpacity: { value: this.settings.opacity },
        uFogDensity: { value: 0.0000055 },
        uFogColor: { value: new THREE.Color('#aebdc9') },
      },
      transparent: true,
      depthWrite: false,
      side: THREE.DoubleSide,
    });

    const segments = Math.min(384, Math.max(96, Math.round(this.resolution * 0.75)));
    const geometry = new THREE.PlaneGeometry(this.spanMeters, this.spanMeters, segments, segments);
    geometry.rotateX(-Math.PI / 2);
    this.surfaceMesh = new THREE.Mesh(geometry, this.surfaceMaterial);
    this.surfaceMesh.frustumCulled = false;
    this.surfaceMesh.renderOrder = 3;
    this.scene.add(this.surfaceMesh);
  }

  /**
   * Uploads a new bed. `heights` is a Float32Array of size×size elevations
   * centred on `offset`. Called whenever the camera moves far enough or the
   * terrain is edited.
   */
  syncBed(heights, connectivity, seaLevel = this.seaLevel) {
    const size = this.resolution;
    const data = this._bedData;
    // The surf channel is derived from the bed, not authored: water that is
    // only a few metres deep next to a beach breaks. Written here so the shader
    // gets a real shoreline field instead of a constant.
    const surfRange = Math.max(6, Math.min(60, this.spanMeters / size * 2.5));
    for (let i = 0; i < size * size; i++) {
      const bed = heights[i];
      const bay = connectivity ? connectivity[i] : bed < seaLevel ? 1 : 0;
      const depth = seaLevel - bed;
      data[i * 4] = bed;
      data[i * 4 + 1] = bay;
      data[i * 4 + 2] = depth > 0 ? (1 - Math.min(1, depth / surfRange)) * (0.35 + 0.65 * bay) : 0;
      data[i * 4 + 3] = 1;
    }
    this.seaLevel = seaLevel;
    this.uploadBed(data);
    this.reset();
  }

  uploadBed(data) {
    if (!this.bedTexture) {
      // Float sampling: LINEAR needs OES_texture_float_linear. Desktop GL always
      // has it; fall back to NEAREST rather than failing to create the texture.
      const gl = this.renderer.getContext();
      const linear = Boolean(gl?.getExtension?.('OES_texture_float_linear'));
      const filter = linear ? THREE.LinearFilter : THREE.NearestFilter;
      this.bedTexture = new THREE.DataTexture(
        data,
        this.resolution,
        this.resolution,
        THREE.RGBAFormat,
        THREE.FloatType
      );
      this.bedTexture.minFilter = filter;
      this.bedTexture.magFilter = filter;
      this.bedTexture.wrapS = THREE.ClampToEdgeWrapping;
      this.bedTexture.wrapT = THREE.ClampToEdgeWrapping;
      this.bedTexture.needsUpdate = true;
      this.initMaterial.uniforms.uBedTex.value = this.bedTexture;
      this.fluxMaterial.uniforms.uBedTex.value = this.bedTexture;
      this.integrateMaterial.uniforms.uBedTex.value = this.bedTexture;
      this.surfaceMaterial.uniforms.uBedTex.value = this.bedTexture;
    } else if (this.bedTexture.image.data !== data) {
      this.bedTexture.image.data = data;
      this.bedTexture.needsUpdate = true;
    } else {
      this.bedTexture.needsUpdate = true;
    }
  }

  setSettings(settings = {}) {
    Object.assign(this.settings, settings);
    const dir = (this.settings.waveDirectionDeg * Math.PI) / 180;
    const waveA = this.initMaterial.uniforms.uWaveA.value;
    waveA.set(Math.cos(dir), Math.sin(dir), this.settings.waveHeight, this.settings.waveLength);
    this.fluxMaterial.uniforms.uWaveA.value.copy(waveA);
    this.integrateMaterial.uniforms.uWaveA.value.copy(waveA);

    const waveB = this.fluxMaterial.uniforms.uWaveB.value;
    waveB.set(
      this.settings.surfStrength,
      this.settings.waveMakerStrength,
      this.settings.foamThreshold,
      this.enabled ? 1 : 0
    );
    this.integrateMaterial.uniforms.uWaveB.value.copy(waveB);

    const u = this.surfaceMaterial.uniforms;
    u.uSwell.value.set(Math.cos(dir), Math.sin(dir), this.settings.waveHeight, this.settings.waveLength);
    u.uChop.value.set(
      this.settings.choppiness,
      this.settings.windSpeed,
      this.settings.detailAmplitude,
      this.seaLevel
    );
    u.uClarity.value = this.settings.clarity;
    u.uFoamAmount.value = this.settings.showFoam ? this.settings.foam : 0;
    u.uOpacity.value = this.settings.opacity;
    u.uSeaLevel.value = this.seaLevel;
    u.uDomain.value.set(this.resolution, this.spanMeters / this.resolution, this.spanMeters, this.seaLevel);
    u.uShallowColor.value.copy?.(this.settings.shallowColor);
    u.uDeepColor.value.copy?.(this.settings.deepColor);
  }

  /** Recentre the simulation domain on the camera focus (metres). */
  setOffset(x, z) {
    this.offset.set(x, z);
    this.surfaceMaterial.uniforms.uOceanOrigin.value.set(x, 0, z);
  }

  reset() {
    const uniforms = this.initMaterial.uniforms;
    uniforms.uDomain.value.set(
      this.resolution,
      this.spanMeters / this.resolution,
      this.spanMeters,
      this.seaLevel
    );
    for (const material of [this.initMaterial, this.fluxMaterial, this.integrateMaterial]) {
      material.uniforms.uDomain.value.set(
        this.resolution,
        this.spanMeters / this.resolution,
        this.spanMeters,
        this.seaLevel
      );
    }
    this.plane.material = this.initMaterial;
    this._renderTo(this.stateA);
    // Clear flux so a re-centre never leaves stale momentum behind.
    this.renderer.setRenderTarget(this.fluxA);
    this.renderer.setClearColor(0x000000, 0);
    this.renderer.clear(true, false, false);
    this.renderer.setRenderTarget(this.fluxB);
    this.renderer.clear(true, false, false);
    this.renderer.setRenderTarget(null);
    this.stateA.texture.needsUpdate = true;
    this.accumulatedTime = 0;
  }

  _renderTo(target) {
    const previous = this.renderer.getRenderTarget();
    this.renderer.setRenderTarget(target);
    this.renderer.render(this.quadScene, this.quadCamera);
    this.renderer.setRenderTarget(previous);
  }

  /**
   * Advances the solver. `substeps` keeps the pipe model stable when the frame
   * rate drops (a 40 m cell needs a shorter dt than a 4 m cell).
   */
  step(deltaSeconds) {
    if (!this.enabled || !this.bedTexture) return;
    const cell = this.spanMeters / this.resolution;
    const cfl = Math.sqrt(cell / this.gravity) * 0.35;
    const steps = Math.max(1, Math.min(6, Math.ceil(deltaSeconds / Math.max(1 / 240, cfl))));
    const dt = Math.min(0.05, deltaSeconds / steps) * Math.max(0.05, this.settings.speed);

    for (let i = 0; i < steps; i++) {
      this.accumulatedTime += dt;
      const sim = this.fluxMaterial.uniforms.uSim.value;
      sim.set(dt, this.accumulatedTime, this.gravity, this.foamLifetime);

      this.fluxMaterial.uniforms.uStateTex.value = this.stateA.texture;
      this.fluxMaterial.uniforms.uFluxTex.value = this.fluxA.texture;
      this.plane.material = this.fluxMaterial;
      this._renderTo(this.fluxB);

      this.integrateMaterial.uniforms.uStateTex.value = this.stateA.texture;
      this.integrateMaterial.uniforms.uFluxTex.value = this.fluxB.texture;
      this.integrateMaterial.uniforms.uSim.value.copy(sim);
      this.plane.material = this.integrateMaterial;
      this._renderTo(this.stateB);

      const swapState = this.stateA;
      this.stateA = this.stateB;
      this.stateB = swapState;
      const swapFlux = this.fluxA;
      this.fluxA = this.fluxB;
      this.fluxB = swapFlux;
    }

    this.surfaceMaterial.uniforms.uStateTex.value = this.stateA.texture;
    this.surfaceMaterial.uniforms.uTime.value = this.accumulatedTime;
  }

  /** Keeps the water shaded by the same sun as the terrain. */
  setSunDirection(direction) {
    this.surfaceMaterial?.uniforms.uSunDir.value.copy(direction);
  }

  /** Sky colours, so reflections match the dome. */
  setSky(zenith, horizon, fogColor) {
    const u = this.surfaceMaterial?.uniforms;
    if (!u) return;
    u.uSkyZenith.value.copy(zenith);
    u.uSkyHorizon.value.copy(horizon);
    if (fogColor) u.uFogColor.value.copy(fogColor);
  }

  dispose() {
    this.stateA.dispose();
    this.stateB.dispose();
    this.fluxA.dispose();
    this.fluxB.dispose();
    this.bedTexture?.dispose();
    this.surfaceMesh.geometry.dispose();
    this.surfaceMaterial.dispose();
    this.initMaterial.dispose();
    this.fluxMaterial.dispose();
    this.integrateMaterial.dispose();
    this.plane.geometry.dispose();
    this.scene.remove(this.surfaceMesh);
  }
}
